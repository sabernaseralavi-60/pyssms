"""Internal-consistency checks of the NGSIM freeway files (writes ``docs/ngsim_checks.md``).

For US-101 and I-80 (first period of each): how far the data set's own acceleration column is from
the difference of its speed column, and how far its speed column is from the difference of its
positions. These numbers are the reason the ten-measure run (``tools/ngsim_ssm1d.py``) derives speed
and acceleration from smoothed positions instead of using those columns.
"""

import glob

import numpy as np

FT = 0.3048
rows = []
for site in ("US-101", "I-80"):
    f = sorted(glob.glob(f"data_raw/ngsim/{site}/vehicle-trajectory-data/*/trajectories-*.txt"))[0]
    a = np.loadtxt(f, usecols=range(14))
    vid, fr, ly, v, acc = a[:, 0], a[:, 1], a[:, 5] * FT, a[:, 11] * FT, a[:, 12] * FT
    o = np.lexsort((fr, vid))
    vid, fr, ly, v, acc = vid[o], fr[o], ly[o], v[o], acc[o]
    same = (vid[1:] == vid[:-1]) & (fr[1:] == fr[:-1] + 1)
    r_acc = (acc[1:] - np.diff(v) / 0.1)[same]
    r_v = (v[1:] - np.diff(ly) / 0.1)[same]
    k = 10
    s2 = (vid[k:] == vid[:-k]) & (fr[k:] == fr[:-k] + k)
    r_w = ((v[k:] + v[:-k]) / 2 - (ly[k:] - ly[:-k]) / (k * 0.1))[s2]
    rows.append(
        f"| {site} | {a.shape[0]:,} | {np.sqrt(np.mean(r_acc**2)):.2f} | "
        f"{np.sqrt(np.mean(r_v**2)):.2f} | {np.sqrt(np.mean(r_w**2)):.2f} | {np.median(r_w):+.3f} |"
    )
text = (
    "# NGSIM internal consistency (freeway files, first period of each)\n\n"
    "*Generated by `tools/ngsim_checks.py`; aggregates only.*\n\n"
    "| site | rows | RMS(acceleration column - d(speed column)/dt), m/s2 | "
    "RMS(speed column - d(position)/dt over 0.1 s), m/s | same over 1 s, m/s | "
    "median difference over 1 s, m/s |\n|---|---|---|---|---|---|\n" + "\n".join(rows) + "\n\n"
    "The median difference of speed is zero (units and reader agree); the scatter is the measurement "
    "noise of the data set. The acceleration column is not the derivative of the speed column.\n"
)
open("docs/ngsim_checks.md", "w", encoding="utf-8").write(text)
print(text)
