"""Share of NGSIM candidate pairs whose bodies overlap at some moment (TTC = 0), per site/period.

Usage: ``python tools/ngsim_overlap_check.py`` (Peachtree and Lankershim periods; smoothed as in the
main run). Writes ``docs/ngsim_overlap.md``. Raw video-based trajectories often contain overlapping
bounding boxes; those pairs count in level A with TTC = 0 in the hierarchy.
"""

import glob
import json
from pathlib import Path

import numpy as np

from pyssms import io, preprocessing, process

rows = []
totals: dict[str, list[int]] = {"smoothed": [0, 0], "raw": [0, 0]}
for site in ("Peachtree", "Lankershim"):
    for f in sorted(glob.glob(f"data_raw/ngsim/{site}/vehicle-trajectory-data/*/trajectories-*.txt")):
        for label, smooth in (("smoothed", True), ("raw", False)):
            tr = io.read_ngsim(f)
            if smooth:
                tr = preprocessing.smooth_trajectories(tr, 5, causal=True)
            pairs = process.candidate_pairs(tr, max_distance=30.0, horizon=10.0)
            n = ov = 0
            for s in range(0, len(pairs), 3000):
                for e in process.encounters(tr, horizon=10.0, pairs=pairs[s : s + 3000]):
                    n += 1
                    fin = np.isfinite(e.ttc)
                    ov += bool(fin.any() and float(np.nanmin(e.ttc)) <= 0.0)
            totals[label][0] += n
            totals[label][1] += ov
            rows.append(f"| {site} {Path(f).parent.name} | {label} | {n:,} | {ov:,} | {100 * ov / n:.2f} |")
            print(rows[-1], flush=True)
text = (
    "# Pairs with overlapping bodies in NGSIM (TTC = 0 at some moment)\n\n"
    "*Generated by `tools/ngsim_overlap_check.py`; aggregates only.*\n\n"
    "| period | trajectories | candidate pairs | pairs with overlap | % |\n|---|---|---|---|---|\n"
    + "\n".join(rows) + "\n"
)
Path("docs/ngsim_overlap.md").write_text(text, encoding="utf-8")
Path("docs/ngsim_overlap.json").write_text(
    json.dumps({k: {"pairs": v[0], "overlap": v[1], "share": v[1] / v[0]} for k, v in totals.items()}, indent=1),
    encoding="utf-8",
)
