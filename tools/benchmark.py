"""Speed of the time-time polygon versus the 32 corner-side combinations.

Writes ``docs/benchmark.md``; every number comes from this script. Usage::

    python tools/benchmark.py
"""

from __future__ import annotations

import platform
import time
from pathlib import Path

import numpy as np

from pyssms import __version__
from pyssms.reference import appendix_a, random_encounters
from pyssms.timetime import indicators

ROOT = Path(__file__).resolve().parents[1]


def best_of(fn, repeat: int = 3) -> float:
    times = []
    for _ in range(repeat):
        t0 = time.perf_counter()
        fn()
        times.append(time.perf_counter() - t0)
    return min(times)


def run_ref(arrays, chunk: int) -> None:
    """The 32-combination reference in blocks of ``chunk`` encounters (cache-friendly).

    ``arrays`` are taken from the encounters once: slicing the properties of the encounter
    object inside the loop would rebuild them for every block and bias the timing.
    """
    c1, v1, c2, v2 = arrays
    for s in range(0, c1.shape[0], chunk):
        k = slice(s, s + chunk)
        appendix_a(c1[k], v1[k], c2[k], v2[k], 1e-9)


def main() -> None:
    rows = []
    for n in (10_000, 100_000, 1_000_000):
        e = random_encounters(n, "generic", 7)
        rep = 3
        # shapes and corners are extracted once, so neither side is charged for building them
        sh1, sh2 = e.shape1, e.shape2
        t_k = best_of(lambda e=e: indicators(sh1, e.pos1, e.vel1, sh2, e.pos2, e.vel2), rep)
        t_g = best_of(
            lambda e=e: indicators(sh1, e.pos1, e.vel1, sh2, e.pos2, e.vel2, fast=False), rep
        )
        arrays = (e.corners1, e.vel1, e.corners2, e.vel2)
        t_r = min(
            best_of(lambda a=arrays, c=c: run_ref(a, c), rep) for c in (n, 20_000, 5_000, 2_000)
        )
        rows.append((n, t_k, t_r, t_g))
    # a plain per-encounter loop, as a straightforward implementation of the appendix would run
    m = 2_000
    e = random_encounters(m, "generic", 7)
    t0 = time.perf_counter()
    for i in range(m):
        appendix_a(
            e.corners1[i : i + 1], e.vel1[i : i + 1], e.corners2[i : i + 1], e.vel2[i : i + 1]
        )
    loop_us = (time.perf_counter() - t0) / m * 1e6

    lines = [
        "# Benchmark",
        "",
        "*Generated by `tools/benchmark.py`; do not edit by hand.* "
        f"pyssms {__version__}, Python {platform.python_version()}, NumPy {np.__version__}, "
        f"{platform.processor() or platform.machine()}; single process, best of 3 "
        "(best-of-3 also at 10^6; absolute times vary by up to a factor of two between runs).",
        "",
        "All four indicators (TTC, TAdv, T2, TG) per encounter.",
        "",
        "| encounters | time-time polygon (s) | 32 combinations, vectorised (s) "
        "| polygon us/encounter |",
        "|---|---|---|---|",
    ]
    lines += [f"| {n:,} | {tk:.2f} | {tr:.2f} | {tk / n * 1e6:.1f} |" for n, tk, tr, _ in rows]
    lines += [
        "",
        "The polygon column uses the 8-row form of K that applies when both rectangles move along "
        "their length (side faces parallel to the axes of the time-time plane; all encounters of "
        "this benchmark). The general 12-row form, which any convex shape and any velocity direction "
        "uses, takes:",
        "",
        "| encounters | general 12-row form (s) | 8-row form (s) | ratio |",
        "|---|---|---|---|",
        *[f"| {n:,} | {tg:.2f} | {tk:.2f} | {tg / tk:.2f} |" for n, tk, _, tg in rows],
        "",
        f"A per-encounter Python loop over the 32 combinations takes {loop_us:.0f} us per "
        "encounter.",
        "",
        "Both columns use the block size that was fastest for them (polygon: "
        "the default, 500 encounters; reference: all at once, 20,000, 5,000 or 2,000). "
        f"At 10^6 encounters the polygon takes {rows[-1][1] / rows[-1][2]:.2f} times the time "
        "of the vectorised combinations. "
        "Its value is exactness in the cases the appendix does not cover (parallel paths, "
        "standing road users, overlapping bodies) and one code path for any convex shape.",
    ]
    (ROOT / "docs" / "benchmark.md").write_text("\n".join(lines) + "\n", "utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
