"""Regenerate docs/validation.md from the validation sets (numbers come from code, never by hand).

Usage: python tools/make_validation_report.py
Adapt `CONTEXTS` to your package: name -> (compute functions, context object).
"""

from __future__ import annotations

from datetime import date
from pathlib import Path

import pyssms
from pyssms import validation as v

OUT = Path(__file__).resolve().parents[1] / "docs" / "validation.md"
CONTEXTS = {
    "example": ({"total": lambda c: (10.2, None), "ratio": lambda c: (1.62, None)}, None),
}


def main() -> None:
    version = pyssms.__version__
    lines = [
        "# Validation against published results",
        "",
        f"*Generated by `tools/make_validation_report.py` on {date.today().isoformat()} with "
        f"version {version}. Do not edit by hand.*",
        "",
    ]
    for name, (compute, ctx) in CONTEXTS.items():
        spec = v.load_spec(name)
        rows = v.run(spec, compute, ctx)
        counts: dict[str, int] = {}
        for r in rows:
            counts[r["status"]] = counts.get(r["status"], 0) + 1
        lines += [
            f"## {spec.title}",
            "",
            f"**Source:** {spec.citation}",
            "",
            f"**Scorecard ({len(rows)} figures):** {counts}",
            "",
            v.to_markdown(rows),
            "### Known gaps",
            "",
        ]
        lines += [f"* **{r['label']}** (`{r['id']}`): {r['note']}" for r in rows if r["note"]]
        lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
